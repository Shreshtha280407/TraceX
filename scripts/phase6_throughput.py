"""Phase 6 throughput and first-useful-output benchmark.

Runs the real ingestion pipeline (HTTP upload -> worker parse/normalize ->
fragment commit -> UTXO graph build -> deterministic findings/features ->
optional ML findings) through the same FastAPI app and worker code the
service runs in production, and times each stage separately. No stage is
mocked or estimated: every number this script prints came from an actual
run on this host.

Two scales:

  * ``--scale 100k`` replays the existing generator-v2 fixture at
    ``datasets/phase5a_100k/ingestion_rows.ndjson`` (already generated by
    ``make dataset``). This is the labelled scenario fixture, unmodified.
  * ``--scale 1m`` (or an explicit ``--rows N``) generates a lightweight
    synthetic linear-chain NDJSON file on the fly. It is deliberately not
    the scenario generator: at this row count the goal is pipeline
    throughput, not detection scenarios, and the scenario generator has
    no size parameter. Every row is schema-valid and is normalized,
    quarantine-checked, and committed exactly like real data.

Stage attribution is honest about what the code actually separates:

  * ``upload_sec`` -- time inside the POST /imports call (hash-while-write
    + immutable publish + DB job row). Wall clock around the HTTP call.
  * ``source_verification_and_parse_commit_sec`` -- worker source-hash
    reverification, plus the parse/normalize/quarantine/fragment-commit
    loop. This is *not* further split because the production code does not
    split it either: ``ingest_source`` runs one batch loop.
  * ``graph_build_sec`` -- ``build_graph_snapshot``, isolated by wrapping
    the exact symbol ``app.engine.ingestion.pipeline`` calls (no production
    code was changed to get this number).
  * ``deterministic_findings_and_features_sec`` -- ``materialize_findings``.
    Phase 4.1 features and deterministic findings are computed in the same
    function in this codebase; reporting them as two numbers would invent a
    split that does not exist in the source.
  * ``ml_findings_sec`` -- the optional unsupervised anomaly stack, if the
    `ml` extra is installed and enabled.

"first useful output" and "first ranked lead" are measured from the moment
the upload HTTP call returns (evidence durably stored, job queued) to graph
completion and to deterministic-findings completion respectively -- this
pipeline builds the graph once after every batch is ingested, not
incrementally per batch, so "first" here honestly means "only", and that is
called out in the printed report rather than implied otherwise.
"""

